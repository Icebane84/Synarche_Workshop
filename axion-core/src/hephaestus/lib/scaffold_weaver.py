_REGISTRY_FILENAME = "scaffold_registry.json"


@dataclass
class StubPointer:
    """A registered stub pointer in the scaffold registry.

    Attributes:
        pointer_id  : unique identifier for this stub (e.g. "STUB-MEM-001").
        file_path   : absolute path of the generated stub file.
        artifact_id : the OMEGA artifact ID this stub belongs to.
        domain      : semantic domain label.
        stub_type   : "class" | "function" | "module".
        status      : "pending" | "filled" | "deprecated".
        created_at  : ISO-8601 creation timestamp.
        metadata    : arbitrary extra fields.
    """

    pointer_id: str
    file_path: str
    artifact_id: str
    domain: str = "CORE"
    stub_type: str = "class"
    status: str = "pending"
    created_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


