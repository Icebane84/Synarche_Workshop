class ScaffoldWeaver:
    """Generates OMEGA-compliant stub files and maintains a pointer registry.

    The ScaffoldWeaver is the PAD-SIP toolkit component responsible for:
    - Generating skeletal stub files for planned components (AOP-LTP-001).
    - Registering each stub as a StubPointer in the scaffold registry.
    - Tracking stub resolution status (pending → filled → deprecated).
    - Providing registry queries for the TransclusionBinder to resolve.

    Usage::

        weaver = ScaffoldWeaver(root_dir="c:/Users/Chris/Synarche_Workspace/axion-core")
        pointer = weaver.weave(
            name="TemporalReasoningEngine",
            stub_type="class",
            target_path="src/logic/reasoning/temporal_engine.py",
            artifact_id="CORE.TEMPORAL.001",
            domain="LOGIC",
            description="Reason about temporal relationships between memory nodes.",
        )
        print(pointer.pointer_id)  # e.g. STUB-LOGIC-001
    """

    def __init__(self, root_dir: Optional[str] = None) -> None:
        """Initialise the weaver with the project root directory.

        Args:
            root_dir: Absolute path to the axion-core project root.
                      Defaults to three levels above this file.
        """
        if root_dir:
            self.root = Path(root_dir)
        else:
            # Resolve: hephaestus/lib/scaffold_weaver.py → axion-core/
            self.root = Path(__file__).resolve().parent.parent.parent.parent

        self._registry_path = self.root / "data" / _REGISTRY_FILENAME
        self._registry: List[StubPointer] = []
        self._load_registry()

        logger.info(f"[SCAFFOLD] ScaffoldWeaver initialised. Registry: {self._registry_path}")

    # ------------------------------------------------------------------
    # §2.1  Registry persistence
    # ------------------------------------------------------------------

    def _load_registry(self) -> None:
        """Load the stub pointer registry from disk."""
        if not self._registry_path.exists():
            self._registry = []
            return
        try:
            with open(self._registry_path, encoding="utf-8") as f:
                data = json.load(f)
            self._registry = [StubPointer(**item) for item in data.get("stubs", [])]
            logger.debug(f"[SCAFFOLD] Loaded {len(self._registry)} pointers from registry.")
        except Exception:
            logger.exception("[SCAFFOLD] Failed to load registry — starting fresh.")
            self._registry = []

    def _save_registry(self) -> None:
        """Persist the stub pointer registry to disk."""
        self._registry_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"stubs": [p.to_dict() for p in self._registry]}
        try:
            with open(self._registry_path, "w", encoding="utf-8") as f:
                json.dump(payload, f, indent=2)
        except Exception:
            logger.exception("[SCAFFOLD] Failed to save registry.")

    # ------------------------------------------------------------------
    # §2.2  Pointer ID generation
    # ------------------------------------------------------------------

    def _generate_pointer_id(self, domain: str) -> str:
        """Generate a sequential pointer ID for a given domain.

        e.g. STUB-LOGIC-003 if two LOGIC stubs already exist.
        """
        domain_upper = domain.upper()
        existing = [p for p in self._registry if p.pointer_id.startswith(f"STUB-{domain_upper}-")]
        return f"STUB-{domain_upper}-{len(existing) + 1:03d}"

    # ------------------------------------------------------------------
    # §2.3  Core weave
    # ------------------------------------------------------------------

    def weave(
        self,
        name: str,
        target_path: str,
        artifact_id: str,
        description: str = "No description provided.",
        stub_type: str = "class",
        domain: str = "CORE",
        overwrite: bool = False,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> StubPointer:
        """Generate a stub file and register the StubPointer.

        Args:
            name        : Python identifier for the class / function / module.
            target_path : path relative to root_dir (e.g. "src/logic/foo.py").
            artifact_id : OMEGA artifact ID string.
            description : human-readable description for the docstring.
            stub_type   : "class" | "function" | "module".
            domain      : OMEGA domain label.
            overwrite   : if False (default) an existing file is NOT overwritten.
            metadata    : optional extra fields stored in the pointer.

        Returns:
            StubPointer: The registered pointer for this stub.

        Raises:
            FileExistsError: If the target file exists and overwrite=False.
        """
        abs_path = self.root / target_path
        pointer_id = self._generate_pointer_id(domain)

        # Guard against overwriting existing implementation
        if abs_path.exists() and not overwrite:
            logger.warning(
                f"[SCAFFOLD] '{abs_path}' already exists. "
                f"Skipping generation (use overwrite=True to force)."
            )
            # Register a pointer that references the existing file
        else:
            template = _TEMPLATES.get(stub_type, _TEMPLATES["module"])
            content = template.format(
                pointer_id=pointer_id,
                artifact_id=artifact_id,
                name=name,
                description=description,
                domain=domain,
                date=datetime.now(timezone.utc).strftime("%Y-%m-%d"),
            )
            abs_path.parent.mkdir(parents=True, exist_ok=True)
            with open(abs_path, "w", encoding="utf-8") as f:
                f.write(content)
            logger.info(f"[SCAFFOLD] Stub generated: {abs_path}")

        pointer = StubPointer(
            pointer_id=pointer_id,
            file_path=str(abs_path),
            artifact_id=artifact_id,
            domain=domain,
            stub_type=stub_type,
            status="pending",
            metadata=metadata or {},
        )
        self._registry.append(pointer)
        self._save_registry()
        return pointer

    # ------------------------------------------------------------------
    # §2.4  Registry management
    # ------------------------------------------------------------------

    def mark_filled(self, pointer_id: str) -> bool:
        """Mark a stub as implemented / filled.

        Args:
            pointer_id: The STUB-xxx-nnn identifier.

        Returns:
            bool: True if the pointer was found and updated.
        """
        for p in self._registry:
            if p.pointer_id == pointer_id:
                p.status = "filled"
                self._save_registry()
                logger.info(f"[SCAFFOLD] Pointer {pointer_id} marked as filled.")
                return True
        logger.warning(f"[SCAFFOLD] Pointer {pointer_id} not found in registry.")
        return False

    def mark_deprecated(self, pointer_id: str) -> bool:
        """Mark a stub as deprecated.

        Args:
            pointer_id: The STUB-xxx-nnn identifier.

        Returns:
            bool: True if found and updated.
        """
        for p in self._registry:
            if p.pointer_id == pointer_id:
                p.status = "deprecated"
                self._save_registry()
                logger.info(f"[SCAFFOLD] Pointer {pointer_id} deprecated.")
                return True
        return False

    def get_pending(self) -> List[StubPointer]:
        """Return all stubs still in 'pending' status."""
        return [p for p in self._registry if p.status == "pending"]

    def get_by_domain(self, domain: str) -> List[StubPointer]:
        """Return all stubs belonging to a domain.

        Args:
            domain: Domain label (case-insensitive).

        Returns:
            List[StubPointer]: Matching pointers.
        """
        return [p for p in self._registry if p.domain.upper() == domain.upper()]

    def get_by_id(self, pointer_id: str) -> Optional[StubPointer]:
        """Return a single pointer by its ID, or None.

        Args:
            pointer_id: The STUB-xxx-nnn identifier.
        """
        for p in self._registry:
            if p.pointer_id == pointer_id:
                return p
        return None

    def registry_report(self) -> Dict[str, Any]:
        """Return a summary of the current registry state."""
        total = len(self._registry)
        pending = sum(1 for p in self._registry if p.status == "pending")
        filled = sum(1 for p in self._registry if p.status == "filled")
        deprecated = sum(1 for p in self._registry if p.status == "deprecated")
        return {
            "total": total,
            "pending": pending,
            "filled": filled,
            "deprecated": deprecated,
            "completion_pct": round((filled / max(1, total)) * 100, 1),
        }

    def __repr__(self) -> str:
        report = self.registry_report()
        return (
            f"<ScaffoldWeaver stubs={report['total']} "
            f"pending={report['pending']} "
            f"filled={report['filled']}>"
        )
