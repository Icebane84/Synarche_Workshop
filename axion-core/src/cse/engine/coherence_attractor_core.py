import logging
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from ..validators.governance_engine import GovernanceEngine, GovernanceVerdict
from ..validators.law_validator import LawValidator

logger = logging.getLogger("PhoenixLogger")


@dataclass
class DissonanceSignature:
    """Represents a specific cognitive, structural, or ethical dissonance identified by the CAC."""

    dissonance_id: str
    severity: str  # "LOW", "MEDIUM", "HIGH", "CRITICAL"
    source: str
    description: str
    suggested_remediation: str


@dataclass
class CoherenceAnalysisResult:
    """Encapsulates the complete coherence telemetry output generated by the CAC."""

    coherence_index: float  # [0.0, 1.0]
    contextual_integrity_score: float  # [0.0, 1.0]
    entropy: float
    is_coherent: bool
    dissonances: List[DissonanceSignature] = field(default_factory=list)
    verdicts: List[GovernanceVerdict] = field(default_factory=list)
    dissonance_quests: List[Dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "coherence_index": round(self.coherence_index, 4),
            "contextual_integrity_score": round(self.contextual_integrity_score, 4),
            "entropy": round(self.entropy, 4),
            "is_coherent": self.is_coherent,
            "dissonances": [
                {
                    "dissonance_id": d.dissonance_id,
                    "severity": d.severity,
                    "source": d.source,
                    "description": d.description,
                    "suggested_remediation": d.suggested_remediation,
                }
                for d in self.dissonances
            ],
            "verdicts": [v.to_dict() for v in self.verdicts],
            "dissonance_quests": self.dissonance_quests,
        }


class CoherenceAttractorCore:
    """CSE-CAC-001: The central nexus that drives the TruthfulnessTracer and processes
    insights from all system components. Acts as the engine's intrinsic drive to resolve dissonance.
    """

    def __init__(self, root_dir: str, governance_engine: Optional[GovernanceEngine] = None) -> None:
        self.root_dir = root_dir
        self.governance_engine = governance_engine or GovernanceEngine()
        self.law_validator = LawValidator(root_dir)

    def evaluate_coherence(
        self,
        loom_state: Dict[str, Any],
        context: Optional[Dict[str, Any]] = None,
    ) -> CoherenceAnalysisResult:
        """Evaluates overall system coherence across governance laws, state vectors, and loom synchronization.

        Args:
            loom_state: Ingested dictionary state from the Loom.
            context: Additional runtime state vector data.

        Returns:
            CoherenceAnalysisResult: Holistic coherence metrics and detected dissonances.
        """
        combined_context: Dict[str, Any] = {**loom_state, **(context or {})}
        dissonances: List[DissonanceSignature] = []

        # 1. Evaluate Law & Mission Drift
        drift_findings = self.law_validator.audit_drift(loom_state)
        for idx, finding in enumerate(drift_findings):
            dissonances.append(
                DissonanceSignature(
                    dissonance_id=f"DIS-LAW-{idx + 1:03d}",
                    severity="HIGH" if "CRITICAL" in finding else "MEDIUM",
                    source="LawValidator",
                    description=finding,
                    suggested_remediation="Synchronize Flattened_Synarche_Synthesis_System_Loom.md with task.md.metadata.json",
                )
            )

        # 2. Evaluate Dynamic Governance Rules
        verdicts = self.governance_engine.evaluate(combined_context)
        for idx, verdict in enumerate(verdicts):
            dissonances.append(
                DissonanceSignature(
                    dissonance_id=f"DIS-GOV-{idx + 1:03d}",
                    severity="HIGH" if "critical" in verdict.effect.lower() else "MEDIUM",
                    source=f"GovernanceRule:{verdict.rule_id}",
                    description=f"Rule triggered for field '{verdict.field}': actual={verdict.actual} vs threshold={verdict.threshold}",
                    suggested_remediation=f"Execute effect handler: {verdict.effect}",
                )
            )

        # 3. Calculate Mathematical Scores
        num_dissonances = len(dissonances)
        entropy = num_dissonances * 0.5

        # Base Coherence Index degrades with entropy
        coherence_index = max(0.0, min(1.0, 1.0 - (entropy * 0.2)))

        # Contextual Integrity Score reflects ratio of clean invariants
        total_checks = max(1, len(drift_findings) + len(verdicts) + 5)
        clean_checks = max(0, total_checks - num_dissonances)
        contextual_integrity_score = clean_checks / total_checks

        is_coherent = coherence_index >= 0.8 and entropy == 0

        # 4. Generate Dissonance Quests for actionable remediation
        quests = []
        for diss in dissonances:
            quests.append(
                {
                    "quest_id": f"QUEST-{diss.dissonance_id}",
                    "title": f"Resolve {diss.source} Dissonance",
                    "severity": diss.severity,
                    "objective": diss.description,
                    "remediation": diss.suggested_remediation,
                    "reward_prestige": 100 if diss.severity == "HIGH" else 50,
                }
            )

        logger.info(
            f"[CAC] Evaluated Coherence: CI={coherence_index:.3f}, CIS={contextual_integrity_score:.3f}, "
            f"Entropy={entropy:.2f}, Dissonances={num_dissonances}"
        )

        return CoherenceAnalysisResult(
            coherence_index=coherence_index,
            contextual_integrity_score=contextual_integrity_score,
            entropy=entropy,
            is_coherent=is_coherent,
            dissonances=dissonances,
            verdicts=verdicts,
            dissonance_quests=quests,
        )
